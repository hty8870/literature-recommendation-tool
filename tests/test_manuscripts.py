def _docx_bytes(
    *,
    body: str | None = None,
    external_link: bool = False,
    external_template: bool = False,
    dtd: bool = False,
    macro: bool = False,
    bomb: bool = False,
) -> bytes:
    if body is None:
        body = (
            '<w:p><w:pPr><w:pStyle w:val="Heading1"/></w:pPr>'
            "<w:r><w:t>Introduction</w:t></w:r></w:p>"
            "<w:p><w:r><w:t>First paragraph.</w:t></w:r></w:p>"
            "<w:tbl><w:tr><w:tc><w:p><w:r><w:t>Table cell text.</w:t></w:r></w:p>"
            "</w:tc></w:tr></w:tbl>"
            '<w:p><w:pPr><w:pStyle w:val="Heading2"/></w:pPr>'
            "<w:r><w:t>Methods</w:t></w:r></w:p>"
            "<w:p><w:r><w:t>We used PCR.</w:t></w:r></w:p>"
        )
    if external_link:
        body += (
            '<w:p><w:hyperlink r:id="rId2"><w:r><w:t>External link</w:t></w:r></w:hyperlink></w:p>'
        )
    document = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        + ('<!DOCTYPE w:document [<!ENTITY xxe "boom">]>' if dtd else "")
        + f'<w:document xmlns:w="{_W}" xmlns:r="{_R}"><w:body>{body}'
        + "<w:sectPr/></w:body></w:document>"
    )
    content_types = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
        '<Default Extension="rels" '
        'ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
        '<Default Extension="xml" ContentType="application/xml"/>'
        '<Override PartName="/word/document.xml" '
        'ContentType="application/vnd.openxmlformats-officedocument.'
        'wordprocessingml.document.main+xml"/>'
        "</Types>"
    )
    package_rels = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        '<Relationship Id="rId1" '
        'Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/'
        'officeDocument" Target="word/document.xml"/>'
        "</Relationships>"
    )
    if external_link:
        relationship = (
            '<Relationship Id="rId2" '
            'Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/'
            'hyperlink" Target="https://doi.org/10.1234/example" TargetMode="External"/>'
        )
    elif external_template:
        relationship = (
            '<Relationship Id="rId3" '
            'Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/'
            'attachedTemplate" Target="https://example.com/template.dotm" '
            'TargetMode="External"/>'
        )
    else:
        relationship = ""
    document_rels = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        + relationship
        + "</Relationships>"
    )
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("[Content_Types].xml", content_types)
        archive.writestr("_rels/.rels", package_rels)
        archive.writestr("word/document.xml", document)
        archive.writestr("word/_rels/document.xml.rels", document_rels)
        if macro:
            archive.writestr("word/vbaProject.bin", b"macro")
        if bomb:
            archive.writestr("word/media/bomb.bin", b"\x00" * 2_000_000)
    return buffer.getvalue()


def _replace_docx_part(package: bytes, part_name: str, content: bytes) -> bytes:
    buffer = io.BytesIO()
    found = False
    with zipfile.ZipFile(io.BytesIO(package)) as source:
        with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
            for info in source.infolist():
                if info.filename == part_name:
                    archive.writestr(info, content)
                    found = True
                else:
                    archive.writestr(info, source.read(info))
            if not found:
                archive.writestr(part_name, content)
    return buffer.getvalue()


def _xml_payload(xml: str, encoding: str) -> bytes:
    if encoding == "utf-8":
        return xml.encode("utf-8")
    xml = xml.replace('encoding="UTF-8"', 'encoding="UTF-16"')
    if encoding == "utf-16le":
        return b"\xff\xfe" + xml.encode("utf-16-le")
    if encoding == "utf-16be":
        return b"\xfe\xff" + xml.encode("utf-16-be")
    raise AssertionError("unexpected XML encoding")


def _docx_entity_attack(part_name: str, encoding: str) -> bytes:
    if part_name == "word/document.xml":
        xml = (
            '<?xml version="1.0" encoding="UTF-8"?>'
            '<!DOCTYPE w:document [<!ENTITY expanded "expanded text">]>'
            f'<w:document xmlns:w="{_W}"><w:body><w:p><w:r><w:t>&expanded;</w:t>'
            "</w:r></w:p></w:body></w:document>"
        )
    elif part_name == "word/_rels/document.xml.rels":
        xml = (
            '<?xml version="1.0" encoding="UTF-8"?>'
            '<!DOCTYPE Relationships [<!ENTITY target "https://example.test">]>'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/'
            '2006/relationships/hyperlink" Target="&target;" TargetMode="External"/>'
            "</Relationships>"
        )
    elif part_name == "word/styles.xml":
        xml = (
            '<?xml version="1.0" encoding="UTF-8"?>'
            '<!DOCTYPE w:styles [<!ENTITY style_name "Heading 1">]>'
            f'<w:styles xmlns:w="{_W}"><w:style w:type="paragraph" w:styleId="Heading1">'
            '<w:name w:val="&style_name;"/></w:style></w:styles>'
        )
    else:
        raise AssertionError("unexpected XML part")
    return _replace_docx_part(_docx_bytes(), part_name, _xml_payload(xml, encoding))


