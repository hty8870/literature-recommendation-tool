def _wait_for_status(
    client: TestClient,
    tenant: str,
    manuscript_id: str,
    *,
    timeout: float = 30.0,
) -> dict:
    deadline = time.time() + timeout
    while time.time() < deadline:
        response = client.get(
            f"/api/v1/manuscripts/{manuscript_id}",
            headers={"X-Tenant-ID": tenant},
        )
        assert response.status_code == 200, response.text
        payload = response.json()
        if payload["parse_status"] in {"ready", "failed"}:
            return payload
        time.sleep(0.05)
    raise AssertionError("manuscript did not finish parsing")


