@pytest.mark.asyncio
async def test_upload_cancellation_waits_for_worker_before_releasing_admission():
    admission = asyncio.Semaphore(1)
    worker_started = threading.Event()
    release_worker = threading.Event()

    def blocking_work():
        worker_started.set()
        release_worker.wait(timeout=5)

    async def upload_work():
        async with admission:
            await _run_sync(blocking_work)

    task = asyncio.create_task(upload_work())
    assert await asyncio.to_thread(worker_started.wait, 2)
    task.cancel()
    await asyncio.sleep(0)
    assert not task.done()
    assert admission.locked()
    release_worker.set()
    with pytest.raises(asyncio.CancelledError):
        await task
    assert not admission.locked()


