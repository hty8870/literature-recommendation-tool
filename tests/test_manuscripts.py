def test_text_bbox_maps_pdfium_char_index_when_range_length_differs(monkeypatch):
    raw = pytest.importorskip("pypdfium2").raw
    monkeypatch.setattr(
        raw,
        "FPDFText_GetCharIndexFromTextIndex",
        lambda textpage, text_index: text_index + (1 if text_index >= 3 else 0),
    )

    class TextPage:
        def get_charbox(self, index):
            return (index * 10.0, 0.0, index * 10.0 + 5.0, 5.0)

    lines = _text_lines(TextPage(), "A\r\nB", 100, use_bbox=True)
    assert [line.text for line in lines] == ["A", "B"]
    assert lines[0].bbox["x0"] == 0
    assert lines[1].bbox["x0"] == 40


def test_line_grouping_merges_physical_lines_but_splits_column_and_vertical_resets():
    def line(text, x0, y0):
        return _Line(
            text=text,
            bbox={"x0": x0, "y0": y0, "x1": x0 + 40, "y1": y0 + 10},
            height=10,
        )

    groups = _group_lines(
        [
            line("first line", 50, 10),
            line("wrapped line", 50, 22),
            line("right column", 250, 100),
            line("left column", 50, 105),
            line("left continuation", 50, 117),
            line("footer", 50, 750),
            line("header", 50, 10),
        ]
    )
    assert [[item.text for item in group] for group in groups] == [
        ["first line", "wrapped line"],
        ["right column"],
        ["left column", "left continuation"],
        ["footer"],
        ["header"],
    ]


def test_digital_pdf_pages_paragraphs_and_coordinates(service_factory):
    pytest.importorskip("pypdfium2")
    service = service_factory()
    status = _upload_and_wait(
        service,
        _digital_pdf_bytes(),
        filename="digital.pdf",
        content_type=PDF_CONTENT_TYPE,
    )
    assert status["parse_status"] == "ready", status
    assert status["page_count"] == 2
    assert status["passage_count"] == 3
    assert status["quality"]["text_page_count"] == 2
    assert status["quality"]["ocr_page_count"] == 0
    assert status["quality"]["reading_order_valid"] is False
    warning_codes = {item["code"] for item in status["warnings"]}
    assert "reading_order_unverified" in warning_codes

    payload = _passages(service, "tenant-a", status["manuscript_id"])
    passages = payload["passages"]
    assert payload["passage_count"] == 3
    assert [(item["page"], item["paragraph_index"]) for item in passages] == [
        (1, 0),
        (1, 1),
        (2, 0),
    ]
    assert passages[0]["text"].splitlines() == [
        "Machine learning improves crop yield.",
        "We observed a significant effect.",
    ]
    assert passages[1]["text"] == "A second paragraph follows here."
    canonical = "".join(passage["text"] + "\n\n" for passage in passages)
    assert status["text_chars"] == len(canonical)
    for passage in passages:
        assert passage["source_method"] == "pdf_text"
        assert passage["ocr_confidence"] is None
        bbox = passage["bbox"]
        assert bbox and bbox["origin"] == "top_left"
        assert bbox["page"] in {1, 2}
        assert 0 <= bbox["x0"] < bbox["x1"] <= 612.01
        assert 0 <= bbox["y0"] < bbox["y1"] <= 792.01
        assert canonical[passage["char_start"] : passage["char_end"]] == passage["text"]
        assert passage["text_sha256"]
    catalog = _status(service, "tenant-a", status["manuscript_id"])
    assert catalog is not None
    assert 0 < len(catalog["catalog"]) <= 3
    assert catalog["catalog"][0]["preview"]
    assert len(catalog["catalog"][0]["preview"]) <= 160
    _record_acceptance(
        "digital-pdf",
        {
            "parse_status": status["parse_status"],
            "page_count": status["page_count"],
            "passage_count": status["passage_count"],
            "text_chars": status["text_chars"],
            "quality": status["quality"],
            "passages": [
                {
                    "page": passage["page"],
                    "text": passage["text"],
                    "bbox": passage["bbox"],
                    "source_method": passage["source_method"],
                }
                for passage in passages
            ],
        },
    )


async def test_read_tool_locates_exact_sentence_on_the_original_pdf_page(service_factory):
    from citation_tool.manuscript_tools import build_manuscript_tools

    pytest.importorskip("pypdfium2")
    service = service_factory()
    status = await asyncio.to_thread(
        _upload_and_wait,
        service,
        _digital_pdf_bytes(),
        filename="digital.pdf",
        content_type=PDF_CONTENT_TYPE,
    )
    assert status["parse_status"] == "ready", status
    document_id = status["manuscript_id"]
    tool = build_manuscript_tools(
        service,
        tenant_id="tenant-a",
        current_manuscript_id=document_id,
        document_ids=[document_id],
        locate_enabled=True,
    )[0]
    quote = "Page two contains a conclusion."
    located = await tool.ainvoke({"view": "verify", "text": quote})
    (row,) = located["matches"]
    assert row["quote"] == quote and row["page"] == row["bbox"]["page"] == 2
    assert row["text"][row["match_start"] - row["start"] : row["match_end"] - row["start"]] == quote
    outside = build_manuscript_tools(
        service,
        tenant_id="tenant-b",
        current_manuscript_id=document_id,
        document_ids=[document_id],
        locate_enabled=True,
    )[0]
    denied = await outside.ainvoke({"view": "verify", "text": quote})
    assert denied["error"]["code"] == "MANUSCRIPT_NOT_FOUND"


