def _record_acceptance(name: str, payload: dict) -> None:
    directory = os.environ.get(ACCEPTANCE_ENV)
    if not directory:
        return
    target = Path(directory)
    target.mkdir(parents=True, exist_ok=True)
    (target / f"case-{name}.json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )


def _acceptance_dir() -> Path | None:
    directory = os.environ.get(ACCEPTANCE_ENV)
    if not directory:
        return None
    target = Path(directory)
    target.mkdir(parents=True, exist_ok=True)
    return target


